export function applyAuthoredPageCompanion(page) {
  const entry = authoredPageCompanions[page.id];
  if (!entry || entry.storyId !== page.storyTemplateId || entry.expectedText !== page.text || entry.expectedAudioUrl !== page.audioNarrationUrl) return page;
  return { ...page, subtitles: structuredClone(entry.subtitles), animationClips: structuredClone(entry.animationClips), audioTracks: (page.audioTracks || []).map((track) => ({ ...track, durationMs: entry.audioDurationMs })) };
}
